export function getDeviceById(id: string): DevicePreset | undefined {
  return DEVICE_PRESETS.find((d) => d.id === id);
}

export function searchDevices(query: string): DevicePreset[] {
  const q = query.toLowerCase().trim();
  if (!q) return DEVICE_PRESETS;
  return DEVICE_PRESETS.filter(
    (d) =>
      d.name.toLowerCase().includes(q) ||
      d.brand.toLowerCase().includes(q) ||
      d.category.toLowerCase().includes(q) ||
      d.series?.toLowerCase().includes(q) ||
      d.id.includes(q)
  );
}

export function filterDevices(opts: {
  brand?: string;
  category?: string;
  query?: string;
}): DevicePreset[] {
  let list = DEVICE_PRESETS;
  if (opts.brand && opts.brand !== "all") {
    list = list.filter((d) => d.brand === opts.brand);
  }
  if (opts.category && opts.category !== "all") {
    list = list.filter((d) => d.category === opts.category);
  }
  if (opts.query) {
    list = searchDevices(opts.query).filter((d) => list.includes(d));
  }
  return list;
}
